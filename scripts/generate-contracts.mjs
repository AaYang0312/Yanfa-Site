import { readFile, readdir, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { compile } from 'json-schema-to-typescript';
import { spawnSync } from 'node:child_process';
import { homedir } from 'node:os';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const files = (await readdir(resolve(root, 'schemas'))).filter(x => x.endsWith('.schema.json')).sort();
const documents = await Promise.all(files.map(async file => JSON.parse(await readFile(resolve(root, 'schemas', file), 'utf8'))));
const definitions = new Map();
for (const document of documents) {
  for (const [name, schema] of Object.entries(document.$defs ?? {})) {
    if (definitions.has(name)) throw new Error(`Duplicate definition: ${name}`);
    definitions.set(name, schema);
  }
}
const refName = schema => schema.$ref.split('/').at(-1);
const acronyms = new Map([['id', 'ID'], ['ids', 'IDs'], ['url', 'URL'], ['urls', 'URLs'], ['sha256', 'SHA256'], ['csrf', 'CSRF'], ['mm', 'MM'], ['mcp', 'MCP']]);
const goName = name => name.split('_').map(x => acronyms.get(x) ?? x[0].toUpperCase() + x.slice(1)).join('');
function go(schema, optional = false) {
  let result;
  if (schema.$ref) result = refName(schema);
  else if (schema.anyOf?.some(x => x.type === 'null')) return `*${go(schema.anyOf.find(x => x.type !== 'null'))}`;
  else if (schema.oneOf) {
    // The wire union is validated before decoding; common fields stay required.
    const variants = schema.oneOf.map(x => definitions.get(refName(x)));
    const properties = Object.assign({}, ...variants.map(x => x.properties));
    const required = variants[0].required.filter(k => variants.every(x => x.required.includes(k)));
    result = go({ type: 'object', properties, required });
  } else if (schema.type === 'array') result = `[]${go(schema.items)}`;
  else if (schema.type === 'object') result = `struct {\n${Object.entries(schema.properties).map(([name, value]) => `\t${goName(name)} ${go(value, !schema.required.includes(name))} \`json:"${name}${schema.required.includes(name) ? '' : ',omitempty'}"\``).join('\n')}\n}`;
  else result = { string: 'string', integer: 'int64', number: 'float64', boolean: 'bool', null: 'any' }[schema.type] ?? 'any';
  return optional && !result.startsWith('[]') && !result.startsWith('*') ? `*${result}` : result;
}
const localReferences = value => {
  if (Array.isArray(value)) return value.map(localReferences);
  if (!value || typeof value !== 'object') return value;
  return Object.fromEntries(Object.entries(value).map(([key, child]) => [key, key === '$ref' ? `#/definitions/${refName(value)}` : localReferences(child)]));
};
const typescript = await compile({
  title: 'Contracts',
  anyOf: [...definitions.keys()].map(name => ({ $ref: `#/definitions/${name}` })),
  definitions: Object.fromEntries([...definitions].map(([name, value]) => [name, { ...localReferences(value), title: name }])),
}, 'Contracts', {
  bannerComment: '// Generated by scripts/generate-contracts.mjs. Edit schemas, then regenerate.',
  format: false,
  ignoreMinAndMaxItems: true,
});
let golang = '// Code generated by scripts/generate-contracts.mjs; DO NOT EDIT.\npackage contract\n\n';
for (const [name, schema] of definitions) {
  golang += `type ${name} ${schema.$ref ? '= ' : ''}${go(schema)}\n\n`;
}
const goBin = process.env.GO_BIN || resolve(homedir(), '.local/share/yuanfa/go1.27.3/bin/go');
const formatted = spawnSync(resolve(dirname(goBin), 'gofmt'), [], { input: golang, encoding: 'utf8' });
if (formatted.error || formatted.status !== 0) throw formatted.error || new Error(formatted.stderr);
golang = formatted.stdout;
await mkdir(resolve(root, 'src/generated'), { recursive: true });
await mkdir(resolve(root, 'backend/internal/contract'), { recursive: true });
await writeFile(resolve(root, 'src/generated/contracts.ts'), typescript.replace(/[ \t]+$/gm, ''));
await writeFile(resolve(root, 'backend/internal/contract/types_generated.go'), golang);
// The browser/admin validator uses precisely the embedded Go source documents.
await writeFile(resolve(root, 'src/generated/schema-documents.json'), JSON.stringify(documents, null, 2) + '\n');
console.log(`Generated ${definitions.size} shared DTOs from ${files.length} schema documents.`);
